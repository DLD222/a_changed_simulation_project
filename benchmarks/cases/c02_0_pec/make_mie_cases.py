#!/usr/bin/env python3
"""Generate the PEC-cylinder Mie convergence cases (continuous-wave incidence).

Incident field: a *continuous* time-harmonic plane wave along +z, produced by a
laser with a user-defined profile:

    laser1.profile = parse_field_function
    laser1.field_function(X,Y,t) = "E0*cos(omega*t)"

`field_function(X,Y,t)` is a 3-variable parser (`Source/Laser/LaserProfilesImpl/
LaserProfileFieldFunction.cpp`) and its return value is the field amplitude in
V/m, so the laser plane acts as a plane-wave source. With
`polarization = 0 1 0` the wave is E parallel to the cylinder axis (Ey);
with `polarization = 1 0 0` it is E perpendicular to the axis (Ex/By).

Geometry: PEC cylinder radius R = 1 m at the origin, domain [-3, 3]^2, PML on all
sides. lambda = 1 m, so ka = 2*pi.

Resolution ladder: dx = 2/10, 2/20, 2/40, 2/80, 2/160 = 0.2 ... 0.0125 (x16).
Each run dumps the main field component every T/8 (T = period) so that the
time-harmonic amplitude can be extracted with an 8-point DFT.

Usage:  python3 make_mie_cases.py [--run]
"""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
C = 299792458.0
LAM = 1.0
OMEGA = 2.0 * math.pi * C / LAM
T = LAM / C
R = 1.0
E0 = 1.0e6
# cells across the 8 m domain: 40, 80, 160, 320, 640  (dx: 0.2 -> 0.0125)
NCELLS = (40, 80, 160, 320, 640)
STOP = 45.0e-9

TEMPLATE = """# Auto-generated by make_mie_cases.py: PEC cylinder, CW plane wave, pol={pol}.
# E parallel to the axis (Ey)   : polarization = 0 1 0
# E perpendicular (Ex, By)      : polarization = 1 0 0
# lambda = 1 m, R = 1 m, ka = 2*pi; domain [-3,3]^2; PML all sides.
# The laser plane at z = -3 emits E0*cos(omega*t) through a user-defined
# profile, i.e. a continuous time-harmonic plane wave travelling along +z.

max_step = 1000000
stop_time = {stop:.6e}

amr.n_cell = {n} {n}
amr.max_grid_size = {n}   # single grid: the CW laser source is unstable across grid boundaries
amr.max_level = 0
geometry.dims = 2
geometry.prob_lo = -4.0 -4.0
geometry.prob_hi =  4.0  4.0

warpx.cfl = 0.4
algo.maxwell_solver = ect
algo.particle_shape = 1
warpx.use_filter = 0

boundary.field_lo = pml pml
boundary.field_hi = pml pml

my_constants.R = {R}
warpx.eb_implicit_function = "R - sqrt(x^2+z^2)"   # positive inside = PEC

my_constants.E0 = {E0:.6e}
my_constants.lam = {lam}
my_constants.omega = {omega:.10e}
lasers.names = laser1
laser1.profile = parse_field_function
laser1.field_function(X,Y,t) = "E0*cos(omega*t)"
laser1.position = 0.0 0.0 -3.0
laser1.direction = 0.0 0.0 1.0
laser1.polarization = {pol_vec}
laser1.wavelength = {lam}
laser1.e_max = {E0:.6e}

diagnostics.diags_names = d1
d1.intervals = {interval}
d1.diag_type = Full
d1.fields_to_plot = {field}
"""

POL = {
    "ey": ("0.0 1.0 0.0", "Ey"),
    "by": ("1.0 0.0 0.0", "By"),
}


def main():
    do_run = "--run" in sys.argv
    bin_2d = os.environ.get(
        "WARPX_BIN", "build_2d/bin/warpx.2d.MPI.OMP.DP.PDP.EB")

    for pol, (pol_vec, field) in POL.items():
        for n in NCELLS:
            dx = 8.0 / n
            dt = 0.4 * dx / (C * math.sqrt(2.0))     # 2D Courant factor
            interval = max(1, int(round(T / 8.0 / dt)))
            name = f"inputs_mie_{pol}_{n}"
            path = os.path.join(HERE, name)
            open(path, "w").write(TEMPLATE.format(
                pol=pol.upper(), stop=STOP, n=n, R=R, E0=E0, lam=LAM,
                omega=OMEGA, pol_vec=pol_vec, interval=interval, field=field))
            print(f"wrote {name}: n={n}, dx={dx:.6g}, dt={dt:.4e}, "
                  f"interval={interval} steps (T/8)")
            if do_run:
                run_dir = os.path.join("/tmp", "mie", f"{pol}_{n}")
                os.makedirs(run_dir, exist_ok=True)
                subprocess.run(["cp", path, os.path.join(run_dir, "inputs")], check=True)
                print(f"  running {run_dir} ...", flush=True)
                with open(os.path.join(run_dir, "run.log"), "w") as log:
                    env = dict(os.environ, OMP_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "8"))
                    subprocess.run([bin_2d, "inputs"], cwd=run_dir, stdout=log,
                                   stderr=subprocess.STDOUT, env=env, check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
