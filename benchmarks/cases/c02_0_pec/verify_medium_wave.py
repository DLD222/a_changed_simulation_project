"""Minimal regression for the uniform-medium ECT kernel (M2b).

What it checks
--------------
A plane wave travelling along +z in a *uniform* dielectric must satisfy:

  1. energy conservation   : the total field energy may not drift by more than `--tol-energy`
                             over the run (no losses, no gain, PEC box);
  2. phase speed           : v = c/sqrt(eps_r) within `--tol-speed`;
  3. amplitude             : |Ey| at the second probe must be within a factor of
                             `--tol-amp` of the first one (a plane wave does not spread
                             in the transverse direction).

Why these three
---------------
They are exactly the quantities that a broken *material* update violates, and they are
insensitive to the interface treatment (there is no interface here).  The current state
of the ECT+material path fails (1) by ~5 orders of magnitude, which is precisely the
kind of failure that the Fresnel tests of M2b cannot see (they are per-resolution and
normalised).

Case layout (must match the runner below)
-----------------------------------------
  domain [-2,2]^2, PEC, EB pushed out of the box, eps_r uniform,
  initial Ey = exp(-((z+1)/0.15)^2), Bx = -Ey/c,
  probes at z_A (default -0.5) and z_B (default 0.3), plus a FieldEnergy diag.

Usage
-----
  python3 verify_medium_wave.py <run_dir> [--epsr 2.25] [--ncell 96]
  python3 verify_medium_wave.py --make /tmp/mreg/uniform --epsr 2.25 --ncell 96 --run

`--make` writes the inputs, `--run` executes WarpX in that directory.
"""
import argparse
import math
import os
import re
import subprocess
import sys

C = 299792458.0
BIN = os.environ.get(
    "WARPX_BIN",
    "build_2d/bin/warpx.2d.MPI.OMP.DP.PDP.EB",
)

TEMPLATE = """# auto-generated by verify_medium_wave.py (uniform medium, ECT)
max_step = 400
amr.n_cell = {n} {n}
amr.max_grid_size = {n}
amr.max_level = 0
geometry.dims = 2
geometry.prob_lo = -2.0 -2.0
geometry.prob_hi =  2.0  2.0
warpx.cfl = 0.4
algo.maxwell_solver = ect
algo.particle_shape = 1
algo.ect_conformal_E = 2
algo.em_solver_medium = macroscopic
macroscopic.epsilon = {epsr}*epsilon0
macroscopic.mu = mu0
macroscopic.sigma = 0
boundary.field_lo = pec pec
boundary.field_hi = pec pec
warpx.eb_implicit_function = "z - 100"
warpx.E_ext_grid_init_style = parse_E_ext_grid_function
warpx.Ex_external_grid_function(x,y,z) = "0"
warpx.Ey_external_grid_function(x,y,z) = "exp(-((z+1.0)/0.15)^2)"
warpx.Ez_external_grid_function(x,y,z) = "0"
warpx.B_ext_grid_init_style = parse_B_ext_grid_function
warpx.Bx_external_grid_function(x,y,z) = "-exp(-((z+1.0)/0.15)^2)/299792458.0"
warpx.By_external_grid_function(x,y,z) = "0"
warpx.Bz_external_grid_function(x,y,z) = "0"
warpx.reduced_diags_names = pA pB pE
pA.type = FieldProbe
pA.intervals = 1
pA.probe_geometry = Point
pA.x_probe = 0.0
pA.z_probe = {za}
pB.type = FieldProbe
pB.intervals = 1
pB.probe_geometry = Point
pB.x_probe = 0.0
pB.z_probe = {zb}
pE.type = FieldEnergy
pE.intervals = 1
"""


def make_case(run_dir, epsr, n, za, zb):
    os.makedirs(run_dir, exist_ok=True)
    with open(os.path.join(run_dir, "inputs"), "w") as f:
        f.write(TEMPLATE.format(n=n, epsr=epsr, za=za, zb=zb))
    return os.path.join(run_dir, "inputs")


def run_case(run_dir):
    env = dict(os.environ, OMP_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "8"))
    with open(os.path.join(run_dir, "run.log"), "w") as f:
        subprocess.run([BIN, "inputs"], cwd=run_dir, stdout=f, stderr=subprocess.STDOUT,
                       env=env, check=False)


def read_probe(path):
    import numpy as np
    d = np.loadtxt(path, skiprows=1)
    return d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    ap.add_argument("--epsr", type=float, default=2.25)
    ap.add_argument("--ncell", type=int, default=96)
    ap.add_argument("--za", type=float, default=-0.5)
    ap.add_argument("--zb", type=float, default=0.3)
    ap.add_argument("--z0", type=float, default=-1.0)
    ap.add_argument("--tol-energy", type=float, default=1.0e-2)
    ap.add_argument("--tol-speed", type=float, default=0.10)
    ap.add_argument("--tol-amp", type=float, default=2.0)
    ap.add_argument("--make", action="store_true")
    ap.add_argument("--run", action="store_true")
    args = ap.parse_args()

    if args.make:
        make_case(args.run_dir, args.epsr, args.ncell, args.za, args.zb)
        print(f"wrote {args.run_dir}/inputs")
    if args.run:
        run_case(args.run_dir)
        print(f"ran WarpX in {args.run_dir}")

    import numpy as np

    ok = True

    # ---- energy
    pe = os.path.join(args.run_dir, "diags/reducedfiles/pE.txt")
    if not os.path.exists(pe):
        print(f"FAIL  missing {pe}")
        return 1
    d = np.loadtxt(pe, skiprows=1)
    e = d[:, 2]
    drift = abs(e[-1] - e[0]) / e[0] if e[0] > 0 else float("inf")
    good = drift <= args.tol_energy
    ok &= good
    print(f"{'OK  ' if good else 'FAIL'} energy   drift={drift:.3e} "
          f"(tol {args.tol_energy:.1e})  E0={e[0]:.4e} max/E0={e.max()/e[0]:.4f}")

    # ---- speed from probe A (distance |za - z0|)
    pa = os.path.join(args.run_dir, "diags/reducedfiles/pA.txt")
    pb = os.path.join(args.run_dir, "diags/reducedfiles/pB.txt")
    dx = 4.0 / args.ncell
    dt = 0.4 * dx / (C * math.sqrt(2.0))
    v_th = C / math.sqrt(args.epsr)

    def arrival(path):
        x = np.loadtxt(path, skiprows=1)
        ey = np.abs(x[:, 6])
        m = ey.max()
        if m <= 0:
            return None, 0.0, 0.0
        idx = int(np.argmax(ey > 0.05 * m))
        return int(x[idx, 0]), m, float(x[np.argmax(ey), 0])

    step_a, amp_a, _ = arrival(pa)
    step_b, amp_b, _ = arrival(pb)
    if step_a is None:
        print("FAIL  probe A never saw the pulse")
        return 1
    dist = abs(args.za - args.z0)
    v_sim = dist / (step_a * dt)
    rel = v_sim / v_th - 1.0
    good = abs(rel) <= args.tol_speed
    ok &= good
    print(f"{'OK  ' if good else 'FAIL'} speed    v={v_sim:.4e} theory={v_th:.4e} "
          f"rel={rel:+.1%} (tol {args.tol_speed:.0%})  arrival={step_a} steps")

    if step_b is None or amp_a <= 0:
        print("FAIL  probe B saw nothing (check probe position / standing-wave node)")
        ok = False
    else:
        ratio = amp_b / amp_a
        good = (ratio <= args.tol_amp) and (ratio >= 1.0 / args.tol_amp)
        ok &= good
        print(f"{'OK  ' if good else 'FAIL'} amplitude ratio B/A={ratio:.3f} "
              f"(A={amp_a:.4f}, B={amp_b:.4f}; tol 1/{args.tol_amp:.0f}..{args.tol_amp:.0f})")

    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
