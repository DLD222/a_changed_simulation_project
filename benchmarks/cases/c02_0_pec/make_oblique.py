#!/usr/bin/env python3
"""Generate an oblique-incidence case (TE or TM polarization, any angle).

Geometry: eb = cos(a)*(x-x0) + sin(a)*(z-z0), PEC on the positive side, incident
pulse travelling along +z.

  TE (s-pol): Ey out of plane, Bx = -Ey/c
  TM (p-pol): Ex in plane, By = Ex/c , Ez = 0

Probes are placed on the specularly reflected beam
k_r_hat = (-sin 2a, cos 2a), at arc length s = 3..8 m from the specular point,
plus an incident probe, a probe inside the conductor, and - for the angle check -
the same set of arc lengths is *not* duplicated: the reflection angle is verified
from the slope of t_ref(s) (see analyze_oblique.py).

Usage:  python3 make_oblique.py <angle_deg> <te|tm> [out_file]
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
S_LIST = (3, 4, 5, 6, 7, 8)

HEADER = """# Auto-generated by make_oblique.py: {pol} polarization, alpha = {angle:g} deg.
#
# Geometry: eb = cos(a)(x-x0) + sin(a)(z-z0), PEC on the positive side.
# Incident pulse along +z:
#   TE: Ey = E0 exp(-((z-zc)/w)^2), Bx = -Ey/c
#   TM: Ex = E0 exp(-((z-zc)/w)^2), By = Ex/c
# Specular reflection: k_r_hat = (-sin 2a, cos 2a).
# Probes sit on that beam at s = 3..8 m; analyze_oblique.py checks the amplitude
# ratio, the beam angle (from the slope of t_ref(s)) and the polarization purity.

max_step = 800
stop_time = 80.0e-9

amr.n_cell = 384 384
amr.max_grid_size = 64
amr.max_level = 0
geometry.dims = 2
geometry.prob_lo = -15.0 -15.0
geometry.prob_hi =  15.0  15.0

warpx.cfl = 0.4
algo.maxwell_solver = ect
algo.particle_shape = 1
warpx.use_filter = 0

boundary.field_lo = pml pml
boundary.field_hi = pml pml

my_constants.alpha = {alpha!r}     # {angle:g} degrees
my_constants.x0 = 0.0
my_constants.z0 = 0.0
warpx.eb_implicit_function = "cos(alpha)*(x-x0) + sin(alpha)*(z-z0)"

my_constants.E0 = 1.0e6
my_constants.zc = -8.0
my_constants.w = 1.5
my_constants.c = 299792458.0
warpx.E_ext_grid_init_style = parse_E_ext_grid_function
warpx.B_ext_grid_init_style = parse_B_ext_grid_function
warpx.Ex_external_grid_function(x,y,z) = "{ex}"
warpx.Ey_external_grid_function(x,y,z) = "{ey}"
warpx.Ez_external_grid_function(x,y,z) = "{ez}"
warpx.Bx_external_grid_function(x,y,z) = "{bx}"
warpx.By_external_grid_function(x,y,z) = "{by}"
warpx.Bz_external_grid_function(x,y,z) = "{bz}"
"""

PULSE = "E0*exp(-((z-zc)/w)^2)"
POL = {
    "te": {"ex": "0", "ey": PULSE, "ez": "0", "bx": f"-{PULSE}/c", "by": "0", "bz": "0"},
    "tm": {"ex": PULSE, "ey": "0", "ez": "0", "bx": "0", "by": f"{PULSE}/c", "bz": "0"},
}


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    angle = float(sys.argv[1])
    pol = sys.argv[2].lower()
    if pol not in POL:
        print("polarization must be 'te' or 'tm'")
        return 2
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        HERE, f"inputs_2d_oblique_{pol}_{int(round(angle))}deg")

    alpha = math.radians(angle)
    text = HEADER.format(pol=pol.upper(), angle=angle, alpha=alpha, **POL[pol])

    names = ["fp_inc", "fp_shadow"] + [f"fp_ref{s}" for s in S_LIST]
    lines = [f"warpx.reduced_diags_names = {' '.join(names)}",
             "fp_inc.type = FieldProbe", "fp_inc.intervals = 2",
             "fp_inc.probe_geometry = Point", "fp_inc.x_probe = 0.0",
             "fp_inc.z_probe = -5.0", ""]
    for s in S_LIST:
        x = -s * math.sin(2 * alpha)
        z = s * math.cos(2 * alpha)
        lines += [f"# Reflected beam, s = {s} m",
                  f"fp_ref{s}.type = FieldProbe", f"fp_ref{s}.intervals = 2",
                  f"fp_ref{s}.probe_geometry = Point",
                  f"fp_ref{s}.x_probe = {x!r}", f"fp_ref{s}.z_probe = {z!r}", ""]
    lines += ["# Inside the conductor: must stay zero.",
              "fp_shadow.type = FieldProbe", "fp_shadow.intervals = 2",
              "fp_shadow.probe_geometry = Point", "fp_shadow.x_probe = 0.0",
              "fp_shadow.z_probe = 4.0", ""]

    open(out, "w").write(text + "\n".join(lines))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
