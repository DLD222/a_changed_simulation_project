"""Generate the PEC-cylinder scattering cases (TE and TM polarization).

Geometry: PEC cylinder of radius R = 1 m at the origin, eb = sqrt(x^2+z^2) - R,
incident plane pulse travelling along +z from zc = -3.5 m.

  TE: Ey out of plane, Bx = -Ey/c      (E parallel to the cylinder axis)
  TM: Ex in plane,      By = Ex/c      (E perpendicular to the axis)

Probes: eight azimuthal positions at r = 2 m (theta measured from +z, so
theta = 0 is the shadow side and theta = 180 deg the specular side), plus one
probe inside the conductor. analyze_cylinder.py checks

  * the field inside the PEC stays ~0,
  * the shadow probe is much weaker than the specular one,
  * the azimuthal pattern is asymmetric and finite (no growth).

Usage:  python3 make_cylinder.py <te|tm> [out_file]
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ASYM = (0, 45, 90, 135, 180, 225, 270, 315)

HEADER = """# Auto-generated by make_cylinder.py: PEC cylinder, {pol} polarization.
#
# eb = sqrt(x^2+z^2) - R  (PEC inside), R = 1 m.
# Incident pulse along +z from zc = -3.5 m:
#   TE: Ey = E0 exp(-((z-zc)/w)^2), Bx = -Ey/c
#   TM: Ex = E0 exp(-((z-zc)/w)^2), By = Ex/c
# Probes at r = 2 m every 45 deg (theta from +z): theta=0 shadow, theta=180
# specular side. One probe inside the conductor must stay zero.

max_step = 700
stop_time = 60.0e-9

amr.n_cell = 256 256
amr.max_grid_size = 64
amr.max_level = 0
geometry.dims = 2
geometry.prob_lo = -5.0 -5.0
geometry.prob_hi =  5.0  5.0

warpx.cfl = 0.4
algo.maxwell_solver = ect
algo.particle_shape = 1
warpx.use_filter = 0

boundary.field_lo = pml pml
boundary.field_hi = pml pml

my_constants.R = 1.0
warpx.eb_implicit_function = "R - sqrt(x^2+z^2)"   # positive inside the cylinder = PEC

my_constants.E0 = 1.0e6
my_constants.zc = -3.5
my_constants.w = 0.8
my_constants.c = 299792458.0
warpx.E_ext_grid_init_style = parse_E_ext_grid_function
warpx.B_ext_grid_init_style = parse_B_ext_grid_function
warpx.Ex_external_grid_function(x,y,z) = "{ex}"
warpx.Ey_external_grid_function(x,y,z) = "{ey}"
warpx.Ez_external_grid_function(x,y,z) = "{ez}"
warpx.Bx_external_grid_function(x,y,z) = "{bx}"
warpx.By_external_grid_function(x,y,z) = "{by}"
warpx.Bz_external_grid_function(x,y,z) = "{bz}"
"""

PULSE = "E0*exp(-((z-zc)/w)^2)"
POL = {
    "te": {"ex": "0", "ey": PULSE, "ez": "0", "bx": f"-{PULSE}/c", "by": "0", "bz": "0"},
    "tm": {"ex": PULSE, "ey": "0", "ez": "0", "bx": "0", "by": f"{PULSE}/c", "bz": "0"},
}


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    pol = sys.argv[1].lower()
    if pol not in POL:
        print("polarization must be 'te' or 'tm'")
        return 2
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, f"inputs_2d_cyl_{pol}")

    text = HEADER.format(pol=pol.upper(), **POL[pol])
    names = [f"p{a}" for a in ASYM] + ["pin"]
    lines = [f"warpx.reduced_diags_names = {' '.join(names)}"]
    r = 2.0
    for a in ASYM:
        th = math.radians(a)
        x, z = r * math.sin(th), r * math.cos(th)
        lines += [f"# r = {r} m, theta = {a} deg (from +z)",
                  f"p{a}.type = FieldProbe", f"p{a}.intervals = 1",
                  f"p{a}.probe_geometry = Point",
                  f"p{a}.x_probe = {x!r}", f"p{a}.z_probe = {z!r}", ""]
    lines += ["# Inside the conductor: must stay zero.",
              "pin.type = FieldProbe", "pin.intervals = 1",
              "pin.probe_geometry = Point", "pin.x_probe = 0.0",
              "pin.z_probe = 0.0", ""]

    open(out, "w").write(text + "\n".join(lines))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
