#!/usr/bin/env python3
"""Fresnel R/T verification of the subpixel (tensor eps^-1) path -- vacuum-reference method.

Why this method
---------------
A two-probe travelling-wave decomposition needs `k(omega)`, and the Yee dispersion is
not `omega/c`; picking the FFT peak and assuming `k = omega/c` makes the 2x2 system
ill-conditioned (symptom: |Er| > |Ei|, R > 1).

Instead we run the SAME case twice:

  A) vacuum reference : eps = 1 everywhere, no interface, same grid / source / probes
  B) with interface   : eps1 = 1, eps2 = 4, interface at z = 0

Both runs share the same Yee dispersion, so `E_ref` already carries the correct
`k_num(omega)` and the subtraction is clean:

  incident side :  E_r = E_tot - E_ref          R = |E_r/E_ref|^2
  transmit side :  T_power = (n2/n1)|E_t/E_ref|^2

No `k`, no `omega` assumption beyond using the *same* omega for A and B (taken from
the reference run's FFT peak).

Usage
-----
  python3 verify_fresnel_rt.py /tmp/fres --eps2 4.0 --ncell 256 --make --run
  python3 verify_fresnel_rt.py /tmp/fres --eps2 4.0 --ncell 256
"""
import argparse
import os
import subprocess
import sys

import numpy as np

C = 299792458.0
BIN = os.environ.get(
    "WARPX_BIN",
    "build_2d/bin/warpx.2d.MPI.OMP.DP.PDP.EB",
)

BASE = """# auto-generated by verify_fresnel_rt.py
max_step = {nsteps}
amr.n_cell = {n} {n}
amr.max_grid_size = {n}
amr.max_level = 0
geometry.dims = 2
geometry.prob_lo = -8.0 -8.0
geometry.prob_hi =  8.0  8.0
warpx.cfl = 0.4
algo.maxwell_solver = yee
algo.particle_shape = 1
algo.em_solver_medium = macroscopic
algo.macroscopic_subpixel = {subpixel}
macroscopic.epsilon = 1.0*epsilon0
macroscopic.epsilon2 = {eps2}*epsilon0
macroscopic.mu = mu0
macroscopic.sigma = 0
{interface_line}
boundary.field_lo = pec pec
boundary.field_hi = pec pec
warpx.pml_ncell = 16  # unused with pec boundaries
warpx.eb_implicit_function = "z - 100"
warpx.E_ext_grid_init_style = parse_E_ext_grid_function
warpx.Ex_external_grid_function(x,y,z) = "0"
warpx.Ey_external_grid_function(x,y,z) = "exp(-((z+1.5)/0.35)^2)*cos(6.283185307179586*(z+1.5)/0.5)"
warpx.Ez_external_grid_function(x,y,z) = "0"
warpx.B_ext_grid_init_style = parse_B_ext_grid_function
warpx.Bx_external_grid_function(x,y,z) = "-exp(-((z+1.5)/0.35)^2)*cos(6.283185307179586*(z+1.5)/0.5)/299792458.0"
warpx.By_external_grid_function(x,y,z) = "0"
warpx.Bz_external_grid_function(x,y,z) = "0"
warpx.reduced_diags_names = q1 q2 q3 q4
diagnostics.diags_names = dEy dBx
dEy.intervals = {nflux}
dEy.diag_type = Full
dEy.fields_to_plot = Ey
dBx.intervals = {nflux}
dBx.diag_type = Full
dBx.fields_to_plot = Bx
q1.type = FieldProbe
q1.intervals = 1
q1.probe_geometry = Point
q1.x_probe = 0.0
q1.z_probe = {z1}
q2.type = FieldProbe
q2.intervals = 1
q2.probe_geometry = Point
q2.x_probe = 0.0
q2.z_probe = {z2}
q3.type = FieldProbe
q3.intervals = 1
q3.probe_geometry = Point
q3.x_probe = 0.0
q3.z_probe = {z3}
q4.type = FieldProbe
q4.intervals = 1
q4.probe_geometry = Point
q4.x_probe = 0.0
q4.z_probe = {z4}
"""


def write_case(d, subpixel, eps2, interface, n, nsteps, z):
    os.makedirs(d, exist_ok=True)
    txt = BASE.format(
        n=n, nsteps=nsteps, subpixel=subpixel, eps2=eps2,
        nflux=max(1, int(round(8.0e-9 / (0.4 * (16.0 / n) / (299792458.0 * 2**0.5))))),
        interface_line=(f'macroscopic.interface_function(x,y,z) = "{interface}"' if interface else
                        '# no dielectric interface (vacuum reference)'),
        z1=z[0], z2=z[1], z3=z[2], z4=z[3])
    with open(os.path.join(d, "inputs"), "w") as f:
        f.write(txt)


def run_case(d):
    env = dict(os.environ, OMP_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "8"))
    with open(os.path.join(d, "run.log"), "w") as f:
        subprocess.run([BIN, "inputs"], cwd=d, stdout=f, stderr=subprocess.STDOUT,
                       env=env, check=False)


def probe(d, tag):
    p = os.path.join(d, "diags/reducedfiles", tag + ".txt")
    x = np.loadtxt(p, skiprows=1)
    # time, Ex, Ey, Bx, By -- the full transverse set is needed for S_z once the
    # medium is anisotropic: S_z = (Ex*By - Ey*Bx)/mu0
    return x[:, 1], x[:, 5], x[:, 6], x[:, 8], x[:, 9]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--eps2", type=float, default=4.0)
    ap.add_argument("--ncell", type=int, default=256)
    ap.add_argument("--nsteps", type=int, default=900)
    ap.add_argument("--tmax-inc", type=float, default=8.0e-9,
                    help="incident-side window end (interface reflection arrived, PEC bounce not yet)")
    ap.add_argument("--tmax-trans", type=float, default=1.8e-8,
                    help="transmission-side window end (slow c/2 wave has arrived)")
    ap.add_argument("--scan", action="store_true", help="scan tmax-inc to check plateauing")
    ap.add_argument("--make", action="store_true")
    ap.add_argument("--run", action="store_true")
    args = ap.parse_args()

    z = (-0.5, 0.8, 0.4, 1.0)
    a_dir = os.path.join(args.root, "vac")
    b_dir = os.path.join(args.root, "med")

    if args.make:
        write_case(a_dir, 0, 1.0, None, args.ncell, args.nsteps, z)
        write_case(b_dir, 1, args.eps2, "-z", args.ncell, args.nsteps, z)
        print("wrote", a_dir, b_dir)
    if args.run:
        for d in (a_dir, b_dir):
            run_case(d)
            print("ran", d)

    n1, n2 = 1.0, np.sqrt(args.eps2)

    # ---- omega from the *reference* run
    t_a, ex_a, ey_a, bx_a, by_a = probe(a_dir, "q1")
    m = t_a <= args.tmax_inc
    n = int(m.sum())
    nfft = 8 * n
    F = np.fft.rfft(ey_a[m] * np.hanning(n), nfft)
    freq = np.fft.rfftfreq(nfft, t_a[1] - t_a[0])
    omega = 2.0 * np.pi * freq[int(np.argmax(np.abs(F)))]

    def dft(d, tag, tmax, comp=2):
        t, ex, ey, bx, by = probe(d, tag)
        f = (ex, ey, bx, by)[comp - 1]
        m = t <= tmax
        return np.sum(f[m] * np.exp(-1j * omega * t[m])) * (t[1] - t[0])

    # ---- incident side: E_r = E_tot - E_ref (both runs, same probe)
    # q1 sees the interface reflection (9.0 ns) and the PEC bounce from z=-4 (9.3 ns)
    # overlapping; with a ~1.7 ns pulse there is no clean window. Use q2 only.
    ref2 = dft(a_dir, "q1", args.tmax_inc)
    tot2 = dft(b_dir, "q1", args.tmax_inc)
    r_c = (tot2 - ref2) / ref2 if ref2 != 0 else np.nan
    R = abs(r_c) ** 2
    ph_r = np.degrees(np.angle(r_c))

    # ---- transmission side
    ref3, ref4 = dft(a_dir, "q3", args.tmax_trans), dft(a_dir, "q4", args.tmax_trans)
    tr3, tr4 = dft(b_dir, "q3", args.tmax_trans), dft(b_dir, "q4", args.tmax_trans)
    T3 = (n2 / n1) * abs(tr3 / ref3) ** 2 if ref3 != 0 else np.nan
    T4 = (n2 / n1) * abs(tr4 / ref4) ** 2 if ref4 != 0 else np.nan
    T = 0.5 * (T3 + T4)

    # ---- Poynting flux, time integrated (a single snapshot is not comparable: the
    # pulse has a different spatial width in the two media). For a 2D plane wave one
    # probe is enough, because nothing varies along x.
    mu0 = 1.25663706212e-6

    def W(d, tag, t1, t2):
        t, ex, ey, bx, by = probe(d, tag)
        m = (t >= t1) & (t <= t2)
        dt_ = t[1] - t[0]
        # S_z = (E x H)_z = (Ex*By - Ey*Bx)/mu0.  For a TE-only field (Ex=By=0)
        # this reduces to -Ey*Bx, so the isotropic P0 numbers are unchanged.
        return np.sum((ex[m]*by[m] - ey[m]*bx[m]) / mu0) * dt_

    R_flux = np.nan
    T_flux = np.nan
    try:
        Wi_ref = W(a_dir, "q1", 2.0e-9, 1.0e-8)
        Wi_tot = W(b_dir, "q1", 2.0e-9, 1.0e-8)
        R_flux = (Wi_ref - Wi_tot) / Wi_ref
        _Rth = ((n1 - n2) / (n1 + n2)) ** 2
        _Tth = 1.0 - _Rth

        Wt_ref = W(a_dir, "q2", 2.0e-9, 1.5e-8)
        Wt_tot = W(b_dir, "q2", 2.0e-9, 1.5e-8)
        T_flux = Wt_tot / Wt_ref

        print(f"R_flux = {R_flux:.4f}   theory {_Rth:.4f}   rel {(R_flux/_Rth-1):+.2%}")
        print(f"T_flux = {T_flux:.4f}   theory {_Tth:.4f}   rel {(T_flux/_Tth-1):+.2%}")
        print(f"R_flux + T_flux = {R_flux+T_flux:.4f}   (should be 1.0000)")
    except Exception as exc:
        print("flux: skipped (%s)" % exc)

    R_th = ((n1 - n2) / (n1 + n2)) ** 2
    T_th = 1.0 - R_th
    print(f"omega = {omega:.4e} rad/s")
    print(f"R      = {R:.4f}   theory {R_th:.4f}   rel {(R/R_th-1):+.2%}   phase {ph_r:+.1f} deg (180)")
    ph_t3 = np.degrees(np.angle(tr3 / ref3)) if ref3 != 0 else np.nan
    ph_t4 = np.degrees(np.angle(tr4 / ref4)) if ref4 != 0 else np.nan
    print(f"T_pow  = {T:.4f}   theory {T_th:.4f}   rel {(T/T_th-1):+.2%}")
    print(f"   per probe: T3={T3:.4f} (phase {ph_t3:+.1f} deg)   T4={T4:.4f} (phase {ph_t4:+.1f} deg)")
    print(f"   probe spread: {abs(T3-T4)/T:.2%}")
    print(f"R + T  = {R+T:.4f}   (should be 1.0000)")

    if args.scan:
        print("tmax-inc scan (R should plateau):")
        for tm in (7.0e-9, 7.5e-9, 8.0e-9, 8.5e-9, 9.0e-9):
            r_ = dft(a_dir, "q2", tm); t_ = dft(b_dir, "q2", tm)
            print(f"   tmax={tm*1e9:.1f} ns  R={abs((t_-r_)/r_)**2:.4f}")

    ok = (abs(R / R_th - 1) <= 0.01 and abs(T / T_th - 1) <= 0.01 and abs(R + T - 1) <= 0.005)
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
